const mediaRoot = 'https://static.wixstatic.com/media';

function imageUrl(source, slug, width = 1800, height = 2200) {
  return `${mediaRoot}/${source}/v1/fit/w_${width},h_${height},q_90/${slug}.jpg`;
}

function thumbnailUrl(source, slug) {
  return `${mediaRoot}/${source}/v1/fill/w_760,h_950,al_c,q_85/${slug}.jpg`;
}

function createPhoto({
  id,
  title,
  source,
  width,
  height,
  year,
  featured = false,
  position = '50% 50%',
}) {
  const slug = title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');

  return {
    id,
    legacyId: id,
    title,
    artist: title,
    source,
    url: imageUrl(source, slug),
    thumbnailUrl: thumbnailUrl(source, slug),
    width,
    height,
    year,
    featured,
    position,
    category: 'Concert',
    alt: `${title} performing live, photographed by Julian Bjørgen.`,
    published: true,
    sortOrder: Number(id),
    managed: false,
  };
}

